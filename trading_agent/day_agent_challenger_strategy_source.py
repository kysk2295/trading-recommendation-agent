    "_leader_allows(_PATCH, candidate) if kind == 'leader_ranking_policy' else "
    "_flow_allows(_PATCH, self._bars, candidate) if kind == 'flow_interpretation_policy' else "
    "_execution_allows(_PATCH, candidate))\n"
    "            return inherited if allowed else None\n"
    "    return DerivedStrategy()\n"
